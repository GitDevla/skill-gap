CREATE TABLE occupations (
    id text PRIMARY KEY CHECK (id ~ '^[a-z0-9-]+$'),
    label text NOT NULL CHECK (label <> ''),
    isco_group text NOT NULL CHECK (isco_group ~ '^[0-9]{4}$')
);

CREATE TABLE skills (
    id text PRIMARY KEY CHECK (id ~ '^[a-z0-9-]+$'),
    label text NOT NULL CHECK (label <> ''),
    skill_type text NOT NULL CHECK (skill_type IN ('skill', 'knowledge'))
);

CREATE TABLE people (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL CHECK (name <> ''),
    email text NOT NULL UNIQUE CHECK (email ~ '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    city text NOT NULL,
    current_occupation_id text NOT NULL REFERENCES occupations,
    target_occupation_id text NOT NULL REFERENCES occupations
);

CREATE TABLE person_skills (
    person_id integer NOT NULL REFERENCES people,
    skill_id text NOT NULL REFERENCES skills,
    has_skill boolean NOT NULL,
    stated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (person_id, skill_id)
);

CREATE TABLE gap_analyses (
    id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    person_id integer NOT NULL REFERENCES people,
    occupation_id text NOT NULL REFERENCES occupations,
    verdict text NOT NULL CHECK (verdict IN ('READY', 'GAP', 'UNKNOWN')),
    verdict_reason text NOT NULL,
    rule_version text NOT NULL,
    vector_store text NOT NULL CHECK (vector_store IN ('qdrant', 'pgvector')),
    evidence jsonb NOT NULL,
    decided_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX gap_analyses_person_idx ON gap_analyses (person_id, decided_at DESC);
